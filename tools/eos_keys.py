"""Writes scripts/Client/Eos/EosKeys.g.cs (not committed) with the Epic Online Services product's keys, from a JSON file
({"productId", "sandboxId", "deploymentId", "clientId", "clientSecret", "encryptionKey"}) given as the argument, or
from the environment (EOS_PRODUCT_ID, EOS_SANDBOX_ID, EOS_DEPLOYMENT_ID, EOS_CLIENT_ID, EOS_CLIENT_SECRET,
EOS_ENCRYPTION_KEY). Without keys the game builds without internet lobbies; without the encryption key (64 hex
characters, never changed once players have saved with it) it builds without cloud saves."""
import json, os, sys

names = ["productId", "sandboxId", "deploymentId", "clientId", "clientSecret"]
env = ["EOS_PRODUCT_ID", "EOS_SANDBOX_ID", "EOS_DEPLOYMENT_ID", "EOS_CLIENT_ID", "EOS_CLIENT_SECRET"]
keys = json.load(open(sys.argv[1])) if len(sys.argv) > 1 else {n: os.environ.get(e, "") for n, e in zip(names, env)}
missing = [n for n in names if not keys.get(n)]
encryption = (keys.get("encryptionKey") if len(sys.argv) > 1 else os.environ.get("EOS_ENCRYPTION_KEY")) or ""
if encryption and (len(encryption) != 64 or any(c not in "0123456789abcdefABCDEF" for c in encryption)):
    sys.exit("the EOS encryption key must be 64 hex characters")
if missing:
    sys.exit("missing EOS keys: " + ", ".join(missing))
here = os.path.dirname(os.path.abspath(__file__))
out = os.path.join(here, "..", "scripts", "Client", "Eos", "EosKeys.g.cs")
args = ", ".join([json.dumps(keys[n]) for n in names] + [json.dumps(encryption)])
with open(out, "w") as f:
    f.write("// Generated by tools/eos_keys.py; not committed.\n#if ARCANUM_EOS\nnamespace Arcanum.Client.Eos;\n\n"
            "internal sealed partial record EosKeys\n{\n    static partial void Load(ref EosKeys? keys) => keys = new(" + args + ");\n}\n#endif\n")
print("wrote", os.path.normpath(out))
