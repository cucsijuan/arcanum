using System.Reflection;
using System.Runtime.CompilerServices;
using System.Text;
using Arcanum.Engine;
using Arcanum.Engine.Core;

namespace Arcanum.Engine.Tests;

/// <summary>
/// Writes the game's copiers (src/Arcanum.Engine/Game.Copiers.g.cs): for each type a copy of the game reaches, code that
/// copies it as <see cref="DeepCopier"/> does through reflection, field by field through accessors to its fields, so a
/// copy needs no reflection (which is very slow where code is compiled ahead of time). The types are found from the
/// game's fields: a field's declared type, the lists, arrays and sets behind a read-only collection interface, and the
/// derived types of a class.
/// </summary>
public static class CopierGenerator
{
    public static string SourcePath([CallerFilePath] string here = "") =>
        Path.GetFullPath(Path.Combine(Path.GetDirectoryName(here)!, "..", "..", "src", "Arcanum.Engine", "Game.Copiers.g.cs"));

    public static string Generate() => new Writer().Write();

    private sealed class Writer
    {
        private readonly Func<FieldInfo, FieldRule> _rules = (Func<FieldInfo, FieldRule>)Delegate.CreateDelegate(typeof(Func<FieldInfo, FieldRule>),
            typeof(Game).GetMethod("CopyRule", BindingFlags.NonPublic | BindingFlags.Static)!);
        private readonly List<Type> _copied = new();      // runtime types with a copier, in the order found
        private readonly HashSet<Type> _seen = new();
        private readonly List<Type> _structs = new();     // value types fixed by a function of their own
        private readonly Dictionary<FieldInfo, string> _accessors = new();
        private readonly Queue<Type> _pending = new();
        private readonly Assembly _engine = typeof(Game).Assembly;
        private int _variables;

        public string Write()
        {
            Reach(typeof(Game));
            while (_pending.Count > 0) Visit(_pending.Dequeue());

            var copiers = new StringBuilder();
            foreach (var type in _copied) copiers.Append(CopierFor(type));
            var fixes = new StringBuilder();
            for (int i = 0; i < _structs.Count; i++) fixes.Append(FixFor(_structs[i], i));

            var sb = new StringBuilder();
            sb.AppendLine("// SPDX-License-Identifier: AGPL-3.0-or-later");
            sb.AppendLine("// <auto-generated> Written by the engine tests (CopierGenerator; ARCANUM_WRITE_COPIERS=1 dotnet test");
            sb.AppendLine("// tests/Arcanum.Engine.Tests --filter GeneratedCopiers). Don't edit. When a field it names is gone, delete this");
            sb.AppendLine("// file (the game is then copied through reflection), build, and write it again. </auto-generated>");
            sb.AppendLine("#nullable disable");
            sb.AppendLine("using System.Runtime.CompilerServices;");
            sb.AppendLine("using Arcanum.Engine.Core;");
            sb.AppendLine();
            sb.AppendLine("namespace Arcanum.Engine;");
            sb.AppendLine();
            sb.AppendLine("public sealed partial class Game");
            sb.AppendLine("{");
            sb.AppendLine("    static partial void RegisterCopiers(Dictionary<Type, Func<object, DeepCopier, object>> copiers)");
            sb.AppendLine("    {");
            for (int i = 0; i < _copied.Count; i++) sb.AppendLine($"        copiers[typeof({Name(_copied[i])})] = GeneratedCopiers.C{i};");
            sb.AppendLine("    }");
            sb.AppendLine();
            sb.AppendLine("    private static class GeneratedCopiers");
            sb.AppendLine("    {");
            sb.Append(copiers);
            sb.Append(fixes);
            foreach (var (field, name) in _accessors)
            {
                var owner = field.DeclaringType!;
                var target = owner.IsValueType ? $"ref {Name(owner)} o" : $"{Name(owner)} o";
                sb.AppendLine($"        [UnsafeAccessor(UnsafeAccessorKind.Field, Name = \"{field.Name}\")] private static extern ref {Name(field.FieldType)} {name}({target});");
            }
            sb.AppendLine("    }");
            sb.AppendLine("}");
            return sb.ToString().Replace("\r\n", "\n");
        }

        // ---- Finding the types ----

        /// <summary>A type a field or an element is declared as: the runtime types it can hold get copiers.</summary>
        private void Reach(Type type)
        {
            if (type.IsValueType)
            {
                if (!DeepCopier.NeedsFixing(type)) return;
                if (Nullable.GetUnderlyingType(type) is { } inner) { Reach(inner); return; }
                if (!_structs.Contains(type)) _structs.Add(type);
                foreach (var f in type.IsGenericType && type.Namespace == "System" ? TupleItems(type) : InstanceFields(type)) Reach(f.FieldType);
                return;
            }
            if (Kept(type)) return;
            if (type == typeof(object)) return; // decided at run time (through reflection if no copier fits)
            if (type.IsInterface)
            {
                foreach (var candidate in CandidatesFor(type)) Enqueue(candidate);
                return;
            }
            if (!type.IsAbstract) Enqueue(type);
            if (!type.IsSealed)
                foreach (var derived in _engine.GetTypes().Where(t => t.IsSubclassOf(type) && !t.IsAbstract)) Enqueue(derived);
        }

        private void Enqueue(Type type)
        {
            if (Kept(type) || !_seen.Add(type)) return;
            _pending.Enqueue(type);
        }

        /// <summary>The types behind a collection interface that the engine's fields hold.</summary>
        private static IEnumerable<Type> CandidatesFor(Type type)
        {
            if (!type.IsGenericType) throw new NotSupportedException($"A field of interface type {type} (not a collection)");
            var def = type.GetGenericTypeDefinition();
            var args = type.GetGenericArguments();
            if (def == typeof(IReadOnlyDictionary<,>) || def == typeof(IDictionary<,>))
                return new[] { typeof(Dictionary<,>).MakeGenericType(args) };
            if (def == typeof(IReadOnlySet<>) || def == typeof(ISet<>))
                return new[] { typeof(HashSet<>).MakeGenericType(args) };
            if (def == typeof(IReadOnlyList<>) || def == typeof(IList<>))
                return new[] { typeof(List<>).MakeGenericType(args), args[0].MakeArrayType() };
            if (def == typeof(IReadOnlyCollection<>) || def == typeof(ICollection<>) || def == typeof(IEnumerable<>))
                return new[] { typeof(List<>).MakeGenericType(args), args[0].MakeArrayType(), typeof(HashSet<>).MakeGenericType(args) };
            throw new NotSupportedException($"A field of interface type {type}");
        }

        private void Visit(Type type)
        {
            _copied.Add(type);
            if (type.IsArray) { Reach(type.GetElementType()!); return; }
            if (CollectionKind(type) is { } kind)
            {
                var args = type.GetGenericArguments();
                if (kind is "HashSet" or "Dictionary" && NeedsCopy(args[0]))
                    throw new NotSupportedException($"{type}: its keys would be copied");
                Reach(args[^1]);
                return;
            }
            if (ListBase(type) is { } list) Reach(list.GetGenericArguments()[0]);
            else if (type.Namespace?.StartsWith("System", StringComparison.Ordinal) == true) throw new NotSupportedException($"Can't copy a {type}");
            Accessible(type);
            foreach (var field in InstanceFields(type))
            {
                var rule = _rules(field);
                if (field.FieldType.IsSubclassOf(typeof(Delegate)) && rule == FieldRule.Copy) throw new NotSupportedException($"{type}.{field.Name} is a delegate");
                if (rule == FieldRule.Copy) Reach(field.FieldType);
            }
        }

        private static string? CollectionKind(Type type)
        {
            if (!type.IsGenericType) return null;
            var def = type.GetGenericTypeDefinition();
            return def == typeof(List<>) ? "List" : def == typeof(HashSet<>) ? "HashSet" : def == typeof(Dictionary<,>) ? "Dictionary"
                : def == typeof(Queue<>) ? "Queue" : null;
        }

        /// <summary>The List&lt;T&gt; an engine type derives from, if any.</summary>
        private static Type? ListBase(Type type)
        {
            for (var t = type.BaseType; t is not null; t = t.BaseType)
                if (t.IsGenericType && t.GetGenericTypeDefinition() == typeof(List<>)) return t;
            return null;
        }

        /// <summary>The instance fields of a type and its base types (up to a system base type).</summary>
        private static IEnumerable<FieldInfo> InstanceFields(Type type)
        {
            for (var t = type; t is not null && t != typeof(object) && t.Namespace?.StartsWith("System", StringComparison.Ordinal) != true; t = t.BaseType)
                foreach (var f in t.GetFields(BindingFlags.Instance | BindingFlags.Public | BindingFlags.NonPublic | BindingFlags.DeclaredOnly))
                    yield return f;
        }

        private static IEnumerable<FieldInfo> TupleItems(Type type) => type.GetFields().Where(f => f.Name.StartsWith("Item", StringComparison.Ordinal));

        /// <summary>Objects of the type are shared by the copy (never changed).</summary>
        private static bool Kept(Type type) => DeepCopier.IsShared(type) && type != typeof(object) && !type.IsInterface;

        private static bool NeedsCopy(Type type) => type.IsValueType ? DeepCopier.NeedsFixing(type) : !Kept(type);

        private static void Accessible(Type type)
        {
            for (var t = type; t.IsNested; t = t.DeclaringType!)
                if (t.IsNestedPrivate && t.DeclaringType != typeof(Game)) throw new NotSupportedException($"{type} is private to {t.DeclaringType}");
        }

        // ---- Writing the code ----

        private string CopierFor(Type type)
        {
            int index = _copied.IndexOf(type);
            var sb = new StringBuilder();
            sb.AppendLine($"        internal static object C{index}(object o, DeepCopier c)");
            if (type.IsArray)
            {
                sb.AppendLine($"            => c.CopyArray(({Name(type)})o, {Element(type.GetElementType()!)});");
                return sb.ToString();
            }
            if (CollectionKind(type) is { } kind)
            {
                var args = type.GetGenericArguments();
                sb.AppendLine(kind switch
                {
                    "List" => $"            => c.CopyList(({Name(type)})o, {Element(args[0])});",
                    "Queue" => $"            => c.CopyQueue(({Name(type)})o, {Element(args[0])});",
                    "HashSet" => $"            => c.CopyHashSet(({Name(type)})o);",
                    _ => $"            => c.CopyDictionary(({Name(type)})o, {Element(args[1])});",
                });
                return sb.ToString();
            }
            sb.AppendLine("        {");
            if (ListBase(type) is { } list)
            {
                // A list of the engine's own: made anew (a field-for-field copy would share its storage), then filled.
                sb.AppendLine($"            var s = ({Name(type)})o;");
                sb.AppendLine($"            var n = new {Name(type)}();");
                sb.AppendLine("            c.Remember(o, n);");
                sb.AppendLine($"            c.FillList(s, n, {Element(list.GetGenericArguments()[0])});");
                foreach (var field in InstanceFields(type))
                    sb.AppendLine($"            {Accessor(field)}(n) = {Fix(field.FieldType, $"{Accessor(field)}(s)")};");
            }
            else
            {
                sb.AppendLine($"            var n = ({Name(type)})c.Shallow(o);");
                foreach (var field in InstanceFields(type))
                {
                    var rule = _rules(field);
                    if (rule == FieldRule.Clear) sb.AppendLine($"            {Accessor(field)}(n) = default;");
                    else if (rule == FieldRule.Copy && NeedsCopy(field.FieldType))
                        sb.AppendLine($"            {Accessor(field)}(n) = {Fix(field.FieldType, $"{Accessor(field)}(n)")};");
                }
            }
            sb.AppendLine("            return n;");
            sb.AppendLine("        }");
            return sb.ToString();
        }

        private string FixFor(Type type, int index)
        {
            var sb = new StringBuilder();
            var name = Name(type);
            sb.AppendLine($"        private static {name} S{index}({name} v, DeepCopier c)");
            sb.AppendLine("        {");
            if (type.IsGenericType && type.Namespace == "System")
            {
                foreach (var item in TupleItems(type).Where(f => NeedsCopy(f.FieldType)))
                    sb.AppendLine($"            v.{item.Name} = {Fix(item.FieldType, $"v.{item.Name}")};");
            }
            else
            {
                Accessible(type);
                foreach (var field in InstanceFields(type).Where(f => NeedsCopy(f.FieldType)))
                    sb.AppendLine($"            {Accessor(field)}(ref v) = {Fix(field.FieldType, $"{Accessor(field)}(ref v)")};");
            }
            sb.AppendLine("            return v;");
            sb.AppendLine("        }");
            return sb.ToString();
        }

        /// <summary>The expression copying <paramref name="value"/> of type <paramref name="type"/>.</summary>
        private string Fix(Type type, string value)
        {
            if (!NeedsCopy(type)) return value;
            if (!type.IsValueType) return $"c.Copy({value})";
            if (Nullable.GetUnderlyingType(type) is { } inner)
            {
                var x = $"x{_variables++}";
                return $"({value} is {{ }} {x} ? ({Name(type)}){Fix(inner, x)} : null)";
            }
            return $"S{_structs.IndexOf(type)}({value}, c)";
        }

        /// <summary>The element copier given to a collection's copy: null when the elements are kept.</summary>
        private string Element(Type type) => NeedsCopy(type) ? $"static (x, c) => {Fix(type, "x")}" : "null";

        private string Accessor(FieldInfo field)
        {
            if (!_accessors.TryGetValue(field, out var name))
            {
                var member = field.Name.StartsWith('<') ? field.Name[1..field.Name.IndexOf('>')] : field.Name.TrimStart('_');
                name = $"A{_accessors.Count}_{field.DeclaringType!.Name.Split('`')[0]}_{member}";
                _accessors[field] = name;
            }
            return name;
        }

        /// <summary>The type's name in C# source.</summary>
        private static string Name(Type type)
        {
            if (type.IsArray) return Name(type.GetElementType()!) + "[]";
            if (Nullable.GetUnderlyingType(type) is { } inner) return Name(inner) + "?";
            if (type.IsByRef) throw new NotSupportedException(type.ToString());
            string name = type.IsNested ? Name(type.DeclaringType!) + "." + type.Name : "global::" + type.Namespace + "." + type.Name;
            if (!type.IsGenericType) return name;
            int tick = name.IndexOf('`');
            if (tick >= 0) name = name[..tick];
            return $"{name}<{string.Join(", ", type.GetGenericArguments().Select(Name))}>";
        }
    }
}
